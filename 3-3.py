'''
文字列の一部をスライスで取り出す方法を説明すること．次の2パターンで，与える整数を省略した場合や，
与える整数が負の場合についても説明すること．
1. 文字列[a:b]
2. 文字列[a:b:c]
クイズ：結果がもももものちになるのは？

1. 'すもももももももものうち'[::2]
2. 'すもももももももものうち'[1::2]
3. 'すもももももももものうち'[::-2]
4. 'すもももももももものうち'[:-1:-2]
'''
# [ クイズ1 ]
s = 'abcdefg'
# [a:b]  aの位置から、bの手前まで取り出す
print(s[1:4])    # bcd
# aを省略すると先頭から、bを省略すると末尾まで
print(s[:3])     # abc
print(s[3:])     # defg
# 負の数は末尾から数える（-1が最後の文字）
print(s[-3:])    # efg
print(s[:-1])    # abcdef

# [a:b:c]  cは何文字おきに取るかを表す（ステップ）
print(s[::2])    # aceg（1つおき）
print(s[1::2])   # bdf
# cが負だと後ろから前へ進む。a, bを省略すると、端から端までが対象になる
print(s[::-1])   # gfedcba（逆順）
print(s[::-2])   # geca
print(s[:-1:-2]) # 末尾（-1の位置）から始めて、-1の手前までなので空文字列になる

t = 'すもももももももものうち'
print(t[::2])
print(t[1::2])
print(t[::-2])
print(t[:-1:-2])
# 答え：2（[1::2]が「もももものち」になる）
