'''
ユニコードスカラ値を文字に変換する方法と，文字のユニコードスカラ値を調べる方法を説明すること．
それを使って，教科書p.98 注釈5を修正すること．
クイズ：円記号は

1. U+005C
2. U+00A5
'''
# [ クイズ1 ]
# 数値 -> 文字：chr（0x771Fは16進数リテラル）
print(chr(0x771F))   # 真（16進数）
print(chr(30495))    # 真（10進数）
# 文字 -> 数値：ord（結果は10進数。16進数で見たいときはhexを使う）
print(hex(ord('\\')))    # 0x5c  '\\'は1個のバックスラッシュ
print(hex(ord('\u00a5')))  # 0xa5  円記号
print(len('\n'))          # 1  改行は1文字
print(len(r'\n'))         # 2  raw文字列はバックスラッシュとnの2文字
# 修正後の注釈5：
# 多くのWindows日本語版では、フォントの都合でバックスラッシュ（U+005C）が
# 円記号のように表示される。表示が同じでも、円記号（U+00A5）とは別の文字なので、
# プログラムではバックスラッシュ（U+005C）を使う。
# 答え：2（円記号はU+00A5）
