'''
引数が素数なら「素数である．」，素数でないなら「素数ではない．」と表示する関数fを，forとrangeを使って
実装すること．引数は整数だと仮定してよい．
クイズ：22801763489は素数であるか？

1. 素数である
2. 素数でない
'''
# [ クイズ1 ]
def f(n):
    # 1以下は素数ではない
    if n < 2:
        print('素数ではない．')
        return
    # 2から√nまでで割り切れる数があれば素数ではない
    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            print('素数ではない．')
            return
    # 最後まで割り切れなければ素数
    print('素数である．')

f(22801763489)
# 答え：1（素数である）
