'''
文字列sの最後に現れるaをbで置換してできる文字列を返す関数fを作って，そのしくみを説明すること．
空文字列を使う場合や，指定した部分文字列が見つからない場合を想定する必要はない．
クイズ：f('すもももももももものうち', 'もも', '桃')の結果は？

1. すもももももも桃のうち
2. す桃もももももものうち
3. す桃桃桃桃のうち
'''
# [ クイズ1 ]
def f(s, a, b):
    # rfindは、aが最後に現れる位置（先頭からの番号）を返す
    i = s.rfind(a)
    # 「その位置より前」+ b + 「aの長さ分を飛ばした残り」をつなげる
    return s[:i] + b + s[i + len(a):]

print(f('すもももももももものうち', 'もも', '桃'))
# 答え：1
